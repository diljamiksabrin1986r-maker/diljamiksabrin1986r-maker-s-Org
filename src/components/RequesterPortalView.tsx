import React, { useMemo, useState } from 'react';
import { Bell, CheckCircle2, ClipboardList, Plus, Send, Trash2 } from 'lucide-react';
import { doc, setDoc, updateDoc } from 'firebase/firestore';
import { createSafeId, db, handleFirestoreError, OperationType } from '../firebase';
import type {
  Product,
  ProductUnit,
  PurchaseRequest,
  PurchaseRequestItem,
  PurchaseRequestStatus,
  UserProfile,
} from '../types';
import { formatMoney } from '../utils/exportReports';

interface RequesterPortalViewProps {
  user: UserProfile;
  products: Product[];
  requests: PurchaseRequest[];
}

const STATUS_TEXT: Record<PurchaseRequestStatus, string> = {
  new: 'Новая (ожидает рассмотрения)',
  reviewing: 'На согласовании у администратора',
  approved: 'Одобрена к закупке',
  rejected: 'Отклонена',
  delivered: 'Доставлена и оприходована',
};

export const RequesterPortalView: React.FC<RequesterPortalViewProps> = ({
  user,
  products,
  requests,
}) => {
  const [supplierName, setSupplierName] = useState('');
  const [comment, setComment] = useState('');
  const [items, setItems] = useState<PurchaseRequestItem[]>([
    {
      name: '',
      category: 'Бакалея',
      unit: 'шт',
      quantity: 10,
      estimatedCost: 1000,
      isNewProduct: true,
    },
  ]);
  const [notice, setNotice] = useState<string | null>(null);
  const [submitting, setSubmitting] = useState(false);

  const myRequests = useMemo(() => {
    if (user.role === 'owner' || user.role === 'admin') return requests;
    return requests.filter((r) => r.requesterId === user.uid);
  }, [requests, user.uid, user.role]);

  const notifications = useMemo(
    () => myRequests.filter((r) => r.unreadForRequester),
    [myRequests]
  );

  const handleMarkRead = async (reqId: string) => {
    try {
      await updateDoc(doc(db, 'purchase_requests', reqId), {
        unreadForRequester: false,
        updatedAt: new Date().toISOString(),
      });
    } catch (err) {
      handleFirestoreError(err, OperationType.UPDATE, `purchase_requests/${reqId}`);
    }
  };

  const handleSelectExistingProduct = (idx: number, prodId: string) => {
    if (!prodId) {
      setItems((prev) =>
        prev.map((item, i) =>
          i === idx ? { ...item, productId: undefined, isNewProduct: true } : item
        )
      );
      return;
    }
    const prod = products.find((p) => p.id === prodId);
    if (!prod) return;
    setItems((prev) =>
      prev.map((item, i) =>
        i === idx
          ? {
              productId: prod.id,
              name: prod.name,
              category: prod.category,
              unit: prod.unit,
              quantity: Math.max(10, prod.minStock),
              estimatedCost: Math.round(Math.max(10, prod.minStock) * prod.costPrice * 100) / 100,
              isNewProduct: false,
            }
          : item
      )
    );
  };

  const handleSubmitRequest = async (e: React.FormEvent) => {
    e.preventDefault();
    const validItems = items.filter((i) => i.name.trim() && i.quantity > 0);
    if (validItems.length === 0) return;

    setSubmitting(true);
    const id = createSafeId('req');
    const now = new Date().toISOString();
    const payload: PurchaseRequest = {
      id,
      requestNumber: `ЗК-${Date.now().toString().slice(-5)}`,
      requesterId: user.uid,
      requesterName: user.displayName,
      supplierName: supplierName.trim(),
      items: validItems,
      isAutoGenerated: false,
      status: 'new',
      comment: comment.trim(),
      unreadForRequester: false,
      createdAt: now,
      updatedAt: now,
    };

    try {
      await setDoc(doc(db, 'purchase_requests', id), payload);
      setSupplierName('');
      setComment('');
      setItems([
        {
          name: '',
          category: 'Бакалея',
          unit: 'шт',
          quantity: 10,
          estimatedCost: 1000,
          isNewProduct: true,
        },
      ]);
      setNotice(`Заявка ${payload.requestNumber} мгновенно отправлена администраторам на согласование.`);
    } catch (err) {
      handleFirestoreError(err, OperationType.CREATE, 'purchase_requests');
    } finally {
      setSubmitting(false);
    }
  };

  return (
    <div className="space-y-5">
      {/* Status Change Notifications */}
      {notifications.length > 0 && (
        <div className="bg-emerald-50 border border-emerald-200 rounded-xl p-4 space-y-2.5">
          <div className="flex items-center gap-2 text-sm font-semibold text-emerald-900">
            <Bell className="w-4 h-4 text-emerald-700" />
            Обновления статусов ваших заявок ({notifications.length})
          </div>
          <div className="space-y-2">
            {notifications.map((req) => (
              <div
                key={req.id}
                className="p-3 bg-white border border-emerald-200 rounded-lg flex flex-wrap items-center justify-between gap-3 text-xs"
              >
                <div>
                  <span className="font-mono font-bold text-slate-900">{req.requestNumber}</span> ·{' '}
                  Статус изменен на: <strong className="text-emerald-700">{STATUS_TEXT[req.status]}</strong>
                  {req.adminNote && <span className="text-slate-600"> · {req.adminNote}</span>}
                </div>
                <button
                  type="button"
                  onClick={() => handleMarkRead(req.id)}
                  className="inline-flex items-center gap-1 px-2.5 py-1 text-xs font-medium text-emerald-700 hover:bg-emerald-50 rounded"
                >
                  <CheckCircle2 className="w-3.5 h-3.5" />
                  Прочитано
                </button>
              </div>
            ))}
          </div>
        </div>
      )}

      {notice && (
        <div className="px-4 py-2.5 rounded-lg border bg-emerald-50 border-emerald-200 text-emerald-900 text-sm flex items-center justify-between">
          <span>{notice}</span>
          <button type="button" onClick={() => setNotice(null)} className="text-xs underline">
            Скрыть
          </button>
        </div>
      )}

      <div className="grid grid-cols-1 lg:grid-cols-12 gap-5 items-start">
        {/* New Purchase Requisition Form */}
        <form
          onSubmit={handleSubmitRequest}
          className="lg:col-span-5 bg-white border border-slate-200 rounded-xl p-5 space-y-4"
        >
          <div className="flex items-center gap-2">
            <ClipboardList className="w-5 h-5 text-emerald-700" />
            <h3 className="text-base font-semibold text-slate-900">
              Подать заявку на закупку товаров
            </h3>
          </div>
          <p className="text-xs text-slate-500">
            Выберите товар из ассортимента или укажите новый товар. Заявка сразу отобразится у администраторов.
          </p>

          <div>
            <label className="block text-xs font-medium text-slate-700 mb-1">
              Рекомендуемый поставщик (необязательно)
            </label>
            <input
              type="text"
              value={supplierName}
              onChange={(e) => setSupplierName(e.target.value)}
              placeholder="Например: Ферма Дубрава"
              className="w-full px-3 py-2 text-sm border border-slate-300 rounded-lg"
            />
          </div>

          <div className="space-y-3">
            {items.map((item, idx) => (
              <div key={idx} className="p-3 bg-slate-50 border border-slate-200 rounded-lg space-y-2.5">
                <div className="flex items-center justify-between">
                  <span className="text-xs font-semibold text-slate-700">Позиция #{idx + 1}</span>
                  {items.length > 1 && (
                    <button
                      type="button"
                      onClick={() => setItems((prev) => prev.filter((_, i) => i !== idx))}
                      className="text-slate-400 hover:text-red-600"
                    >
                      <Trash2 className="w-3.5 h-3.5" />
                    </button>
                  )}
                </div>

                <select
                  value={item.productId || ''}
                  onChange={(e) => handleSelectExistingProduct(idx, e.target.value)}
                  className="w-full px-2.5 py-1.5 text-xs border border-slate-300 rounded bg-white"
                >
                  <option value="">+ Новый товар (ввести вручную)</option>
                  {products.map((p) => (
                    <option key={p.id} value={p.id}>
                      {p.name} (остаток: {p.stock} {p.unit})
                    </option>
                  ))}
                </select>

                <input
                  type="text"
                  required
                  placeholder="Название товара"
                  value={item.name}
                  onChange={(e) =>
                    setItems((prev) =>
                      prev.map((x, i) => (i === idx ? { ...x, name: e.target.value } : x))
                    )
                  }
                  className="w-full px-2.5 py-1.5 text-sm border border-slate-300 rounded bg-white"
                />

                <div className="grid grid-cols-3 gap-2">
                  <input
                    type="number"
                    min="1"
                    placeholder="Кол-во"
                    value={item.quantity}
                    onChange={(e) =>
                      setItems((prev) =>
                        prev.map((x, i) =>
                          i === idx ? { ...x, quantity: Number(e.target.value) || 0 } : x
                        )
                      )
                    }
                    className="px-2.5 py-1.5 font-mono text-xs border border-slate-300 rounded bg-white"
                  />
                  <select
                    value={item.unit}
                    onChange={(e) =>
                      setItems((prev) =>
                        prev.map((x, i) =>
                          i === idx ? { ...x, unit: e.target.value as ProductUnit } : x
                        )
                      )
                    }
                    className="px-2 py-1.5 text-xs border border-slate-300 rounded bg-white"
                  >
                    <option value="шт">шт</option>
                    <option value="кг">кг</option>
                    <option value="л">л</option>
                    <option value="уп">уп</option>
                  </select>
                  <input
                    type="number"
                    min="0"
                    placeholder="Бюджет (смн)"
                    value={item.estimatedCost}
                    onChange={(e) =>
                      setItems((prev) =>
                        prev.map((x, i) =>
                          i === idx ? { ...x, estimatedCost: Number(e.target.value) || 0 } : x
                        )
                      )
                    }
                    className="px-2.5 py-1.5 font-mono text-xs border border-slate-300 rounded bg-white"
                  />
                </div>
              </div>
            ))}

            <button
              type="button"
              onClick={() =>
                setItems((prev) => [
                  ...prev,
                  {
                    name: '',
                    category: 'Бакалея',
                    unit: 'шт',
                    quantity: 10,
                    estimatedCost: 1000,
                    isNewProduct: true,
                  },
                ])
              }
              className="inline-flex items-center gap-1 text-xs font-medium text-emerald-700 hover:underline"
            >
              <Plus className="w-3.5 h-3.5" />
              Добавить еще позицию
            </button>
          </div>

          <div>
            <label className="block text-xs font-medium text-slate-700 mb-1">
              Комментарий к заявке
            </label>
            <textarea
              rows={2}
              value={comment}
              onChange={(e) => setComment(e.target.value)}
              placeholder="Срочность, пожелания покупателей..."
              className="w-full px-3 py-2 text-sm border border-slate-300 rounded-lg"
            />
          </div>

          <button
            type="submit"
            disabled={submitting}
            className="w-full inline-flex items-center justify-center gap-2 py-2.5 text-sm font-semibold text-white bg-emerald-600 rounded-lg hover:bg-emerald-700 disabled:opacity-50"
          >
            <Send className="w-4 h-4" />
            {submitting ? 'Отправка...' : 'Отправить заявку администратору'}
          </button>
        </form>

        {/* Request Status Tracking */}
        <div className="lg:col-span-7 bg-white border border-slate-200 rounded-xl p-5 space-y-4">
          <h3 className="text-base font-semibold text-slate-900">
            Отслеживание статусов заказов и заявок ({myRequests.length})
          </h3>
          {myRequests.length === 0 ? (
            <div className="py-12 text-center text-sm text-slate-500">
              Вы еще не отправляли заявок на закупку.
            </div>
          ) : (
            <div className="space-y-3">
              {myRequests.map((req) => (
                <div key={req.id} className="p-4 rounded-lg border border-slate-200 space-y-2">
                  <div className="flex flex-wrap items-center justify-between gap-2">
                    <div className="flex items-center gap-2 text-sm">
                      <span className="font-mono font-bold text-slate-900">{req.requestNumber}</span>
                      <span className="text-slate-400">·</span>
                      <span className="text-xs text-slate-500">
                        {req.createdAt.slice(0, 16).replace('T', ' ')}
                      </span>
                    </div>
                    <span
                      className={`text-xs font-semibold ${
                        req.status === 'approved' || req.status === 'delivered'
                          ? 'text-emerald-700'
                          : req.status === 'rejected'
                          ? 'text-red-700'
                          : 'text-amber-700'
                      }`}
                    >
                      {STATUS_TEXT[req.status]}
                    </span>
                  </div>

                  <div className="text-xs text-slate-700">
                    {req.items.map((i) => `${i.name} (${i.quantity} ${i.unit})`).join(', ')}
                  </div>

                  <div className="flex items-center justify-between text-xs text-slate-500 pt-1 border-t border-slate-100">
                    <span>{req.adminNote ? `Ответ: ${req.adminNote}` : 'Ожидает обновления'}</span>
                    <span className="font-mono font-semibold text-slate-900">
                      ~{formatMoney(req.items.reduce((a, b) => a + b.estimatedCost, 0))}
                    </span>
                  </div>
                </div>
              ))}
            </div>
          )}
        </div>
      </div>
    </div>
  );
};
